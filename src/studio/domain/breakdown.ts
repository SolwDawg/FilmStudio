import { DEFAULT_STORY_PROMPT, DURATION_PLACEHOLDER } from "./prompts.js";
import type { FilmScene } from "./project.js";

export interface ShotDetail {
  number: number;
  character?: string;
  location?: string;
  action: string;
  microExpression?: string;
  dialogue?: {
    speaker: string;
    text: string;
  };
  cameraDirective?: string;
  raw: string;
}

export interface StructuredScene {
  id: string;
  sceneNumber: number;
  rawText: string;
  characters: string[];
  location?: string;
  shots: ShotDetail[];
  cut: boolean;
}

/**
 * Splits a long story or prose text into chunks of roughly `wordsPerChunk` words
 * while respecting sentence boundaries (., !, ?, \n).
 */
export function chunkStory(text: string, wordsPerChunk = 150): string[] {
  const clean = text.trim();
  if (!clean) return [];

  const sentences = clean.split(/(?<=[.!?\n])\s+/).filter(Boolean);
  const chunks: string[] = [];
  let currentWords: string[] = [];

  for (const sentence of sentences) {
    const words = sentence.trim().split(/\s+/).filter(Boolean);
    if (currentWords.length + words.length > wordsPerChunk && currentWords.length > 0) {
      chunks.push(currentWords.join(" "));
      currentWords = [...words];
    } else {
      currentWords.push(...words);
    }
  }

  if (currentWords.length > 0) {
    chunks.push(currentWords.join(" "));
  }

  return chunks;
}

/**
 * Builds the full instruction prompt for an LLM to break a story chunk down into SCENEs,
 * each sized for one `durationSeconds` clip (the project's `film.duration`).
 */
export function buildStoryChunkPrompt(chunk: string, customPrompt?: string, durationSeconds = 8): string {
  const instructions = (customPrompt?.trim() ? customPrompt : DEFAULT_STORY_PROMPT)
    .trim()
    .replaceAll(DURATION_PLACEHOLDER, String(durationSeconds));
  return `${instructions}

--- VĂN BẢN TRUYỆN / Ý TƯỞNG CẦN PHÂN TÍCH: ---
${chunk.trim()}
`;
}

const SCENE_BLOCK_REGEX = /(?:^|\n)[ \t]*(?:PHÂN\s+CẢNH|CẢNH|SCENE)\s*(\d+)?[ \t]*[:.\-–]?[ \t]*(.*?)(?=(?:\n[ \t]*(?:PHÂN\s+CẢNH|CẢNH|SCENE)\s*(?:\d+)?[ \t]*[:.\-–]?)|$)/gis;
const CUT_MARKER = /\[(?:CUT|CẮT CẢNH)\]/gi;

/**
 * Parses structured SCENE text generated by Gemini or authored by user.
 */
export function parseStructuredScript(scriptText: string): StructuredScene[] {
  const scenes: StructuredScene[] = [];
  const matches = [...scriptText.matchAll(SCENE_BLOCK_REGEX)];

  if (matches.length === 0) {
    // If no explicit SCENE markers, treat the entire body as a single scene
    const cut = CUT_MARKER.test(scriptText);
    const cleaned = scriptText.replace(CUT_MARKER, "").trim();
    if (cleaned) {
      scenes.push({
        id: "scene-01",
        sceneNumber: 1,
        rawText: cleaned,
        characters: extractCharactersFromBlock(cleaned),
        location: extractLocationFromBlock(cleaned),
        shots: extractShotsFromBlock(cleaned),
        cut
      });
    }
    return scenes;
  }

  const width = Math.max(2, String(matches.length).length);

  for (const [index, match] of matches.entries()) {
    const rawNumber = match[1] ? Number.parseInt(match[1], 10) : index + 1;
    const body = (match[2] ?? "").trim();
    const cut = CUT_MARKER.test(body);
    const cleaned = body.replace(CUT_MARKER, "").trim();

    scenes.push({
      id: `scene-${String(index + 1).padStart(width, "0")}`,
      sceneNumber: rawNumber,
      rawText: cleaned,
      characters: extractCharactersFromBlock(cleaned),
      location: extractLocationFromBlock(cleaned),
      shots: extractShotsFromBlock(cleaned),
      cut
    });
  }

  return scenes;
}

function extractCharactersFromBlock(text: string): string[] {
  const charLine = text.match(/(?:Nhân vật|Characters?|Diễn viên)\s*[:–-]\s*([^\n]+)/i);
  if (charLine?.[1]) {
    return charLine[1]
      .split(/[,;&]/)
      .map((s) => s.trim())
      .filter((s) => s.length > 0 && !/^(none|không có)$/i.test(s));
  }
  return [];
}

function extractLocationFromBlock(text: string): string | undefined {
  const locLine = text.match(/(?:Bối cảnh|Location|Địa điểm)\s*[:–-]\s*([^\n]+)/i);
  return locLine?.[1]?.trim() || undefined;
}

function extractShotsFromBlock(text: string): ShotDetail[] {
  const shotRegex = /(?:^|\n)[ \t]*(?:Shot|Góc quay)\s*(\d*)[ \t]*[:–-][ \t]*([^\n]+(?:\n(?![ \t]*(?:Shot|Góc quay))[^\n]+)*)/gi;
  const shots: ShotDetail[] = [];
  const matches = [...text.matchAll(shotRegex)];

  for (const [index, match] of matches.entries()) {
    const num = match[1] ? Number.parseInt(match[1], 10) : index + 1;
    const content = match[2].trim();

    // Check for dialogue: "Name: text" or Name: "text"
    // Speaker names may be hyphenated ("Seo-yeon").
    const dialogueMatch = content.match(/([A-ZÀ-Ỹa-zà-ỹ0-9_ -]+)\s*[:–]\s*["“]([^"”]+)["”]/);

    shots.push({
      number: num,
      action: content,
      dialogue: dialogueMatch ? { speaker: dialogueMatch[1].trim(), text: dialogueMatch[2].trim() } : undefined,
      raw: content
    });
  }

  return shots;
}

// Scenes for a story pasted into the dashboard: a structured script ("SCENE n:" blocks) keeps its
// scenes, with cast and [CUT] markers; plain prose becomes one scene per ~wordsPerChunk words.
export function scenesFromStory(storyText: string, wordsPerChunk = 150): FilmScene[] {
  const parsed = parseStructuredScript(storyText);
  if (parsed.length > 0) {
    return parsed.map((scene) => ({
      id: scene.id,
      title: `Scene ${scene.sceneNumber}`,
      prompt: scene.rawText,
      characters: scene.characters,
      cut: scene.cut,
      shotImages: [],
      connectShot: false
    }));
  }
  const chunks = chunkStory(storyText, wordsPerChunk);
  const width = Math.max(2, String(chunks.length).length);
  return chunks.map((chunk, index) => ({
    id: `scene-${String(index + 1).padStart(width, "0")}`,
    title: `Scene ${index + 1}`,
    prompt: chunk,
    characters: [],
    cut: false,
    shotImages: [],
    connectShot: false
  }));
}
